const languageTags = {en: 'en', zh: 'zh-CN', 'zh-TW': 'zh-TW', ja: 'ja-JP', de: 'de-DE'};

function languageFor(value = '') {
 const tag = String(value).toLowerCase().replaceAll('_', '-');
 if (/^zh-(tw|hk|mo|hant)\b/.test(tag)) return 'zh-TW';
 if (/^zh(?:-|$)/.test(tag)) return 'zh';
 if (/^ja(?:-|$)/.test(tag)) return 'ja';
 if (/^de(?:-|$)/.test(tag)) return 'de';
 return 'en';
}

function translate(language, key, parameters = {}) {
 const template = messages[language]?.[key] ?? messages.en[key] ?? key;
 return template.replace(/\{(\w+)\}/g, (match, name) => parameters[name] ?? match);
}

return {messages, languageTags, languageFor, translate};
