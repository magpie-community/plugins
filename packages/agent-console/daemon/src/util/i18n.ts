export function tr(key: string, params?: Record<string, string | number>): string {
  let s = dict[locale][key] ?? dict.en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}
