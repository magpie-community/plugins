/**
 * Liveness of the recorded instance: its controller port must answer. The
 * state file alone lies when the spawned mihomo died (a stop/start race, a
 * crash), while magpie keeps aiming at its ports.
 */
export async function instanceAlive() {
  const s = readState();
  if (!s) return false;
  // The controller port is the only honest signal: a dead instance cannot
  // answer it, and a recycled pid cannot fake it. Deliberately no
  // process.kill(pid, 0) here — bun's first such call on Windows costs 3.6s,
  // which used to eat a fifth of magpie's plugin load budget on every start.
  return await portOpen(s.controllerPort, 800);
}

function waitForController(port, ms = 12000) {
  const start = Date.now();
  return (async () => {
    for (;;) {
      if (await portOpen(port, 800)) return true;
      if (Date.now() - start > ms) return false;
      await new Promise((r) => setTimeout(r, 300));
    }
  })();
}

/** Start the per-node listener instance. Returns the state object. */
function readLogTail(file, lines = 8) {
  try {
    const text = fs.readFileSync(file, 'utf8').trim();
    return text.split(/\r?\n/).slice(-lines).join(' | ');
  } catch { return ''; }
}

// Async on purpose: the plugin loads inside magpie's 20s budget, so a start
// that runs in the background must not block the host's event loop. spawnSync
// here cost 9s of frozen host per restart.
function spawnText(cmd, argv, opts = {}) {
  const { timeout = 25000, ...rest } = opts;
  return new Promise((resolve) => {
    let child;
    try {
      child = spawn(cmd, argv, { windowsHide: true, ...rest });
    } catch (error) {
      resolve({ status: -1, stdout: '', stderr: '', error });
      return;
    }
    let out = '';
    let err = '';
    let timer = null;
    let done = false;
    const finish = (r) => {
      if (done) return;
      done = true;
      if (timer) clearTimeout(timer);
      resolve(r);
    };
    if (child.stdout) child.stdout.setEncoding('utf8');
    if (child.stderr) child.stderr.setEncoding('utf8');
    child.stdout?.on('data', (d) => { out += d; });
    child.stderr?.on('data', (d) => { err += d; });
    if (timeout > 0) {
      timer = setTimeout(() => {
        try { child.kill(); } catch {}
        finish({ status: -1, stdout: out, stderr: err, error: new Error('spawn timeout') });
      }, timeout);
    }
    child.on('error', (e) => finish({ status: -1, stdout: out, stderr: err, error: e }));
    child.on('close', (code) => finish({ status: code, stdout: out, stderr: err, error: null }));
  });
}

// Windows fallback launch chain (only when a plain detached spawn is refused):
// Node -> PowerShell (router-spawn.ps1) -> WMI Create -> cmd.exe /c router-run.cmd -> mihomo.
//  * Parenting mihomo under WmiPrvSE keeps the node ports alive across a
//    magpie plugin reload or exit, and succeeds where a detached child of the
//    host is refused.
//  * WMI only receives `cmd.exe /c <that file>`: the mihomo command line lives
//    in router-run.cmd, so the WMI call stays a short ASCII string.
//  * The pid is resolved afterwards from the mihomo command line, which
//    carries our config path.
function writeLaunchCmd(file, exe, args, logFile) {
  const q = (s) => `"${s}"`;
  const script = ['@echo off', [q(exe), ...args.map(q), '>', q(logFile), '2>&1'].join(' '), ''].join('\r\n');
  // cmd.exe parses .cmd bytes in the OEM codepage; these paths are ASCII.
  fs.writeFileSync(file, script, 'latin1');
  return file;
}

function psQuote(s) { return "'" + String(s).replace(/'/g, "''") + "'"; }

function writeSpawnPs(file) {
  const script = [
    'param([Parameter(Mandatory=$true)][string]$CmdLine)',
    '$r = Invoke-CimMethod -ClassName Win32_Process -MethodName Create -Arguments @{ CommandLine = $CmdLine }',
    'exit $r.ReturnValue',
  ].join('\r\n');
  fs.writeFileSync(file, Buffer.from('\uFEFF' + script + '\r\n', 'utf8'));
  return file;
}

async function findRouterPidByPS(configPath, procName = 'mihomo.exe') {
  const out = await spawnText('powershell.exe', [
    '-NoProfile', '-NonInteractive', '-Command',
    `[Console]::OutputEncoding=[System.Text.Encoding]::UTF8; Get-CimInstance Win32_Process -Filter "Name='${procName}'" | ` +
    `Where-Object { $_.CommandLine -like '*${configPath.replace(/'/g, "''")}*' } | ` +
    'Select-Object -First 1 -ExpandProperty ProcessId',
  ], { timeout: 15000 });
  const n = Number(out.stdout.trim().split(/\r?\n/)[0]);
  return Number.isInteger(n) && n > 0 ? n : 0;
}

// A pid in router.json is only a hint: Windows reuses pids after a reboot or a
// crash, so taskkill /PID <stale> can hit an unrelated process that now owns
// the number. Confirm the recorded pid still belongs to *this* router — its
// image name must match the spawned exe and its command line must reference
// the generated config — before killing it.
async function pidMatchesRouter(pid, configPath, procName = 'mihomo.exe') {
  const n = Number(pid);
  if (!Number.isInteger(n) || n <= 0) return false;
  const out = await spawnText('powershell.exe', [
    '-NoProfile', '-NonInteractive', '-Command',
    `[Console]::OutputEncoding=[System.Text.Encoding]::UTF8; Get-CimInstance Win32_Process -Filter "ProcessId=${n}" | ` +
    `Where-Object { $_.Name -eq '${procName.replace(/'/g, "''")}' -and $_.CommandLine -like '*${String(configPath).replace(/'/g, "''")}*' } | ` +
    'Select-Object -First 1 -ExpandProperty ProcessId',
  ], { timeout: 15000 });
  return out.stdout.trim().split(/\r?\n/)[0] === String(n);
}

/** Does this pid still exist? Only used to clear locks left by a dead host. */
export async function pidAlive(pid) {
  const n = Number(pid);
  if (!Number.isInteger(n) || n <= 0) return false;
  const r = await spawnText('tasklist', ['/FI', `PID eq ${n}`, '/NH', '/FO', 'CSV'], { timeout: 8000 });
  return r.status === 0 && r.stdout.includes(`"${n}"`);
}

async function waitForRouterPid(pidFile, configPath, procName, ms = 10000) {
  const start = Date.now();
  for (;;) {
    try {
      const n = Number(fs.readFileSync(pidFile, 'utf8').trim());
      if (Number.isInteger(n) && n > 0) return n;
    } catch { /* not written yet */ }
    if (Date.now() - start > ms) break;
    await new Promise((r) => setTimeout(r, 250));
  }
  return await findRouterPidByPS(configPath, procName);
}

// Outbound NIC of this instance. With the main Clash in TUN mode the virtual
// adapter grabs the default route with the lowest metric, and virtual NICs
// (Radmin VPN etc.) can sort first by InterfaceMetric — so resolve the
// default-route table against Get-NetAdapter -Physical (TUN adapters are
// never "physical") before falling back to a name filter.
const TUN_IF_RE = /(mihomo|clash|meta|sing|tun|tap|wintun|wireguard|loopback|虚拟|回环|vmware|virtualbox|hyper-v|vethernet|bluestacks|vpn|radmin|zerotier|tailscale|openvpn|hamachi|vgate|utun)/i;
let ifCache = { at: 0, name: '' };

const PHYS_ROUTE_PS =
  '[Console]::OutputEncoding=[System.Text.Encoding]::UTF8; ' +
  '$p=@{}; Get-NetAdapter -Physical -ErrorAction SilentlyContinue | ForEach-Object { $p[[int]$_.ifIndex] = $_.Name }; ' +
  'Get-NetRoute -DestinationPrefix \'0.0.0.0/0\' -AddressFamily IPv4 -ErrorAction SilentlyContinue | ' +
  'Sort-Object { $_.RouteMetric + $_.InterfaceMetric } | ' +
  'ForEach-Object { if ($p.ContainsKey([int]$_.InterfaceIndex)) { $p[[int]$_.InterfaceIndex]; break } }';

export async function detectInterface(maxAgeMs = 300000) {
  if (process.platform !== 'win32') return '';
  const t = Date.now();
  if (ifCache.at && t - ifCache.at < maxAgeMs) return ifCache.name;
  let name = '';
  try {
    const out = await spawnText('powershell.exe', [
      '-NoProfile', '-NonInteractive', '-Command', PHYS_ROUTE_PS,
    ], { timeout: 15000 });
    name = out.stdout.split(/\r?\n/).map((s) => s.trim()).filter(Boolean)[0] || '';
  } catch { /* keep '' */ }
  if (!name) {
    try {
      const out = await spawnText('powershell.exe', [
        '-NoProfile', '-NonInteractive', '-Command',
        '[Console]::OutputEncoding=[System.Text.Encoding]::UTF8; Get-NetIPInterface -AddressFamily IPv4 -ConnectionState Connected -ErrorAction SilentlyContinue | Sort-Object InterfaceMetric | ForEach-Object { $_.InterfaceAlias }',
      ], { timeout: 15000 });
      for (const line of out.stdout.split(/\r?\n/)) {
        const s = line.trim();
        if (s && !TUN_IF_RE.test(s)) { name = s; break; }
      }
    } catch { /* keep '' */ }
  }
  if (name && TUN_IF_RE.test(name)) name = '';
  ifCache = { at: t, name };
  return name;
}

export async function startRouter(nodes, opts = {}) {
  if (!Array.isArray(nodes) || nodes.length === 0) throw new Error('没有选中任何节点，节点池为空');
  const exe = opts.exe || findExe();
  if (!exe) throw new Error('找不到 mihomo.exe（设置 MIHOMO_EXE 指向它）');
  const procName = path.basename(exe).toLowerCase();
  const mainConfig = opts.mainConfig || findMainConfig();
  if (!mainConfig) throw new Error('找不到 Clash 主配置（设置 MIHOMO_CONFIG）');
  const basePort = opts.basePort ?? DEFAULT_BASE_PORT;
  const controllerPort = opts.controllerPort ?? DEFAULT_CONTROLLER_PORT;
  const secret = opts.secret || randomSecret();

  const prev = readState();
  if (prev) {
    await stopRouter({ quiet: true }).catch(() => {});
    // A fresh spawn that races the dying predecessor loses the bind and
    // exits silently, leaving magpie aimed at dead ports — wait it out.
    // The controller port closing is the same signal as the process leaving,
    // and unlike tasklist/process.kill it costs milliseconds.
    if (prev.controllerPort) {
      const t0 = Date.now();
      while ((await portOpen(prev.controllerPort, 400)) && Date.now() - t0 < 8000) {
        await new Promise((r) => setTimeout(r, 200));
      }
    }
  }

  const text = fs.readFileSync(mainConfig, 'utf8');
  const mapping = stablePortMapping(nodes, basePort);
  const interfaceName = opts.interfaceName !== undefined ? opts.interfaceName : await detectInterface();
  const cfg = buildConfig(text, nodes, {
    basePort, controllerPort, mapping, proxyBlocks: opts.proxyBlocks, interfaceName, secret,
  });
  fs.mkdirSync(stateDir(), { recursive: true });
  fs.writeFileSync(configPath(), cfg);

  // Validate before spawning: a merged config with bad indentation otherwise
  // dies silently and every assigned account port goes dead.
  const check = await spawnText(exe, ['-t', '-d', stateDir(), '-f', configPath()], { timeout: 20000 });
  if (check.status !== 0 || /test failed|configuration file.*failed/i.test(check.stdout + check.stderr)) {
    const detail = [check.stderr, check.stdout].filter(Boolean).join(' | ').trim().split(/\r?\n/).slice(-4).join(' | ');
    throw new Error(`mihomo 配置校验失败${detail ? `：${detail}` : ''}（${configPath()}）`);
  }

  const logFile = path.join(stateDir(), 'router.log');
  const pidFile = path.join(stateDir(), 'router.pid');
  try { fs.writeFileSync(logFile, ''); } catch {}
  try { fs.rmSync(pidFile, { force: true }); } catch {}

  const spawnDetached = () => {
    const child = spawn(exe, ['-d', stateDir(), '-f', configPath()], { detached: true, stdio: 'ignore' });
    child.unref();
    try { fs.writeFileSync(pidFile, String(child.pid)); } catch {}
    return child;
  };

  if (process.platform === 'win32') {
    // Prefer an ordinary detached child — same as on macOS/Linux. It stays in
    // magpie's process tree, which a host kill cleans up; only when that child
    // is refused (some machines won't let an unsigned plugin host spawn a
    // detached binary) do we fall back to the WMI launch below.
    const child = spawnDetached();
    const upDirect = await waitForController(controllerPort, 6000);
    if (!upDirect) {
      // Detached spawn was refused or died instantly. WMI parents the new
      // process under WmiPrvSE instead of magpie, which keeps the node ports
      // alive across a magpie reload/exit — and gets a launch that a plain
      // detached spawn could not.
      try { child.kill(); } catch { /* already gone */ }
      const cmdFile = writeLaunchCmd(path.join(stateDir(), 'router-run.cmd'), exe,
        ['-d', stateDir(), '-f', configPath()], logFile);
      const spawnPs = writeSpawnPs(path.join(stateDir(), 'router-spawn.ps1'));
      const cmdExe = path.join(process.env.SystemRoot || 'C:\\Windows', 'System32', 'cmd.exe');
      // No quotes anywhere: these ASCII paths contain no spaces, and WMI passes
      // the string through verbatim, so quoting only leaks into the child's argv.
      const cmdLine = `${cmdExe} /c ${cmdFile}`;
      const psExe = path.join(process.env.SystemRoot || 'C:\\Windows',
        'System32', 'WindowsPowerShell', 'v1.0', 'powershell.exe');
      const launched = await spawnText(psExe, [
        '-NoProfile', '-NonInteractive', '-ExecutionPolicy', 'Bypass',
        '-File', spawnPs, '-CmdLine', cmdLine,
      ], { timeout: 25000 });
      if (launched.status !== 0) {
        throw new Error(`启动 mihomo 失败：WMI 返回 ${launched.status}${launched.stderr ? `：${launched.stderr.trim()}` : ''}`);
      }
    }
  } else {
    spawnDetached();
  }

  const up = await waitForController(controllerPort);
  if (!up) {
    // The process may still be alive but failed to bind; report honestly.
    const port0 = await portOpen(basePort, 1000);
    if (!port0) {
      const tail = readLogTail(logFile);
      throw new Error(`mihomo 没起来：控制器 ${controllerPort} / 节点端口 ${basePort} 未监听${tail ? `；日志：${tail}` : ''}（${configPath()}）`);
    }
  }
  // The controller answering means mihomo is already running, so its pid can
  // be read straight from WMI; polling the pid file first would only add
  // seconds of dead time (nothing writes it on the WMI path).
  let pid = process.platform === 'win32' ? await findRouterPidByPS(configPath(), procName) : 0;
  if (!pid) pid = await waitForRouterPid(pidFile, configPath(), procName, 3000);
  if (pid) { try { fs.writeFileSync(pidFile, String(pid)); } catch {} }

  const ports = {};
  for (const [name, port] of Object.entries(mapping)) ports[name] = await portOpen(port, 1200);
  const state = {
    pid, exe, mainConfig, config: configPath(), basePort, controllerPort, secret,
    nodes: nodes.slice(), mapping, ports,
    startedAt: new Date().toISOString(),
  };
  writeState(state);
  return state;
}

export async function stopRouter(opts = {}) {
  const s = readState();
  if (!s) { if (!opts.quiet) throw new Error('没有运行中的节点实例'); return null; }
  let pid = s.pid;
  if (!pid && s.config) {
      try { pid = await findRouterPidByPS(s.config, path.basename(s.exe || 'mihomo.exe').toLowerCase()); } catch { pid = 0; }
  }
  if (pid) {
    if (process.platform === 'win32') {
      // The recorded pid is only trusted after the check above: a recycled
      // pid belongs to someone else and must not be taskkilled.
      const ours = s.config ? await pidMatchesRouter(pid, s.config, path.basename(s.exe || 'mihomo.exe').toLowerCase()) : true;
      if (ours) {
        try { await spawnText('taskkill', ['/PID', String(pid), '/T', '/F'], { stdio: 'ignore', timeout: 8000 }); }
        catch { /* already gone */ }
      }
    } else {
      try { process.kill(pid, 'SIGTERM'); } catch { /* already gone */ }
    }
  }
  try { fs.unlinkSync(statePath()); } catch {}
  try { fs.unlinkSync(path.join(stateDir(), 'router.pid')); } catch {}
  return s;
}

/** Measure node latency through our own instance's controller. */
export async function testDelays(names, opts = {}) {
  const st = readState();
  const port = opts.controllerPort ?? st?.controllerPort ?? DEFAULT_CONTROLLER_PORT;
  const secret = opts.secret ?? st?.secret ?? '';
  const timeout = opts.timeout ?? 5000;
  const target = { kind: 'tcp', host: '127.0.0.1', port, secret };
  const url = opts.url || 'http://www.gstatic.com/generate_204';
  const out = {};
  let i = 0;
  const worker = async () => {
    for (;;) {
      const idx = i++;
      if (idx >= names.length) return;
      const n = names[idx];
      try {
        const r = await request(target, 'GET',
          `/proxies/${encodeURIComponent(n)}/delay?timeout=${timeout}&url=${encodeURIComponent(url)}`,
          null, { timeout: timeout + 5000 });
        out[n] = typeof r.json?.delay === 'number' ? r.json.delay : null;
      } catch { out[n] = null; }
    }
  };
  const n = Math.max(1, Math.min(opts.concurrency ?? 8, names.length));
  await Promise.all(Array.from({ length: n }, worker));
  return out;
}

export function routerStatus() {  const s = readState();
  if (!s) return { running: false };
  // Seed the stable port table from an instance started before it existed,
  // so a later rebuild keeps every node on the port an account points at.
  try {
    if (!Object.keys(readPorts()).length && s.mapping && Object.keys(s.mapping).length) {
      fs.writeFileSync(portsPath(), JSON.stringify(s.mapping, null, 2));
    }
  } catch { /* best effort */ }
  return { running: true, ...s, proxyUrls: Object.fromEntries(
    Object.entries(s.mapping || {}).map(([n, p]) => [n, `http://127.0.0.1:${p}`]),
  ) };
}
