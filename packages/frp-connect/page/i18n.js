export const LANGS = Object.keys(WORDS);

// word is the page's word in a window's language: en, zh, or the first
// part of a tag (zh-TW → zh). English for anything else.
export function word(lang, name) {
  const tag = String(lang || "en");
  const table = WORDS[tag] || WORDS[tag.split("-")[0]] || WORDS.en;
  return table[name] ?? WORDS.en[name] ?? name;
}

// t is the page's words for a window in lang: t("save"), or t("pid") of
// something.
export function words(lang) {
  return (name) => word(lang, name);
}
